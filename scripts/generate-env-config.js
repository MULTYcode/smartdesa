/**
 * Script to generate public/env-config.js from .env file.
 * Used during local development to populate window.__ENV
 * so that getRuntimeEnv() works on the client side.
 * 
 * In production (Docker/K8s), docker-entrypoint.sh handles this instead.
 */

const fs = require('fs');
const path = require('path');

const ENV_FILE = path.resolve(__dirname, '..', '.env');
const OUTPUT_FILE = path.resolve(__dirname, '..', 'public', 'env-config.js');

// Only read NEXT_PUBLIC_ prefixed variables
const NEXT_PUBLIC_PREFIX = 'NEXT_PUBLIC_';

function parseEnvFile(filePath) {
  const env = {};
  
  if (!fs.existsSync(filePath)) {
    console.warn('[generate-env-config] No .env file found at:', filePath);
    return env;
  }

  const content = fs.readFileSync(filePath, 'utf-8');
  const lines = content.split('\n');

  for (const line of lines) {
    const trimmed = line.trim();
    // Skip empty lines and comments
    if (!trimmed || trimmed.startsWith('#')) continue;

    const eqIndex = trimmed.indexOf('=');
    if (eqIndex === -1) continue;

    const key = trimmed.substring(0, eqIndex).trim();
    let value = trimmed.substring(eqIndex + 1).trim();

    // Remove surrounding quotes if present
    if ((value.startsWith('"') && value.endsWith('"')) ||
        (value.startsWith("'") && value.endsWith("'"))) {
      value = value.slice(1, -1);
    }

    // Only include NEXT_PUBLIC_ variables
    if (key.startsWith(NEXT_PUBLIC_PREFIX)) {
      env[key] = value;
    }
  }

  return env;
}

function generateEnvConfig() {
  const env = parseEnvFile(ENV_FILE);
  
  const entries = Object.entries(env)
    .map(([key, value]) => `  ${key}: "${value}"`)
    .join(',\n');

  const content = `// Auto-generated by scripts/generate-env-config.js at ${new Date().toISOString()}
// DO NOT EDIT — this file is regenerated on every \`npm run dev\`.
window.__ENV = {
${entries}
};
`;

  fs.writeFileSync(OUTPUT_FILE, content, 'utf-8');
  console.log(`[generate-env-config] Generated ${OUTPUT_FILE} with ${Object.keys(env).length} variables`);
}

generateEnvConfig();
